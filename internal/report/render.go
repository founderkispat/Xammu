package report

import (
	"encoding/json"
	"fmt"
	"strings"
	"time"

	"xammu/internal/contracts"
)

// JSON renders the report exactly as C-15 defines it. The document a reviewer signs is
// this one; the markdown is a view of it, never a second authority.
func JSON(rep *contracts.Report) ([]byte, error) {
	raw, err := json.MarshalIndent(rep, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("report: cannot marshal the C-15: %w", err)
	}
	return append(raw, '\n'), nil
}

// Markdown renders the same payload for a human reader. Nothing here measures: every
// number is read back out of the report argument, so a disagreement between the two
// formats is impossible by construction.
func Markdown(rep *contracts.Report) string {
	var b strings.Builder
	b.WriteString("# XAMMU defensive-behaviour report\n\n")
	b.WriteString(fmt.Sprintf("| run | state | target | partition | generated | schema |\n"))
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	b.WriteString(fmt.Sprintf("| %s | %s | %s | %s | %s | %s |\n\n",
		rep.RunID, rep.RunState, rep.TargetOrigin, rep.Partition,
		rep.GeneratedAt.Format(time.RFC3339), rep.SchemaVersion))
	b.WriteString(fmt.Sprintf("Authorization `%s`, valid until %s. Stopped because: %s\n\n",
		rep.AuthorizationRef, utc(rep.AuthorizationValidUntil), rep.StateReason))
	b.WriteString(fmt.Sprintf("Budget: %d of %d authorized requests spent in %d second(s).\n\n",
		rep.RequestsUsed, rep.RequestBudget, rep.DurationSeconds))

	b.WriteString("## Executive summary\n\n")
	for _, s := range rep.ExecutiveSummary {
		b.WriteString("- " + s + "\n")
	}
	b.WriteString("\n### Limits the run could not exceed\n\n")
	for _, s := range rep.LimitsSummary {
		b.WriteString("- " + s + "\n")
	}

	b.WriteString("\n## The five dimensions\n\n")
	b.WriteString(renderDimensions(rep.Dimensions))

	b.WriteString("## Coverage matrix\n\n")
	b.WriteString(rep.Matrix.Basis + "\n\n")
	b.WriteString(renderMatrix(rep.Matrix))
	b.WriteString("\n### Cells this run did not measure\n\n")
	for _, s := range rep.Matrix.NotMeasured {
		b.WriteString("- " + s + "\n")
	}

	b.WriteString("\n## Findings\n\n")
	if len(rep.Findings) == 0 {
		b.WriteString("None published.\n")
	}
	for _, f := range rep.Findings {
		b.WriteString(renderFinding(f))
	}

	b.WriteString("\n## Counted views (distributions)\n\n")
	b.WriteString(renderDistributions(rep.Distributions))

	b.WriteString("\n## Residual risk: three statements kept apart\n\n")
	b.WriteString(renderRisk(rep.ResidualRisk))

	b.WriteString("## Unevaluated zones\n\n")
	if rep.UnevaluatedNone {
		b.WriteString("The run declares this section empty: every zone the pipeline recorded is listed in " +
			"the findings, and nothing else was left unread.\n")
	}
	for _, z := range rep.Unevaluated {
		b.WriteString(fmt.Sprintf("- **%s** (reason `%s`)\n", z.Scope, z.Reason))
		b.WriteString("  - Detail: " + z.Detail + "\n")
		b.WriteString("  - Remediation: " + z.Remediation + "\n")
		b.WriteString("  - Reproduce: `" + z.ReproductionCommand + "`\n")
		b.WriteString(fmt.Sprintf("  - Planned requests not spent: %d\n", z.PlannedRequests))
	}

	b.WriteString("\n## Evidence and reproducibility\n\n")
	e := rep.Evidence
	b.WriteString(fmt.Sprintf("- Manifest: `%s` (digest `%s`)\n", e.ManifestPath, e.ManifestDigest))
	b.WriteString(fmt.Sprintf("- Verify: `%s`\n", e.VerifyCommand))
	b.WriteString(fmt.Sprintf("- Observations: %d across round(s) %s\n", e.ObservationCount,
		joinLines(e.RoundIDs, ", ")))
	b.WriteString(fmt.Sprintf("- Corpus: `%s`; detector set: `%s`; tool: `%s`; generated by: `%s`\n",
		e.CorpusCommitRef, e.DetectorSetHash, e.ToolVersion, e.GeneratedByUser))

	b.WriteString("\n## Declared out of scope\n\n")
	for _, s := range rep.OutOfScope {
		b.WriteString("- " + s + "\n")
	}
	b.WriteString("\n## Contract versions\n\n")
	b.WriteString(joinLines(versionsOf(rep.ContractVersions), "; ") + "\n")
	return b.String()
}

func renderFinding(f contracts.DiscoveryFinding) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("### %s - %s (`%s`, priority %s)\n\n", f.Ref, f.FindingType, f.Priority,
		string(f.Priority)))
	b.WriteString(fmt.Sprintf("- Scope: %s\n", f.AffectedScope))
	if f.AttackClass != "" || f.Vector != "" || f.Encoding != "" {
		b.WriteString(fmt.Sprintf("- Grid position: class=%s vector=%s encoding=%s\n",
			orNone(string(f.AttackClass)), orNone(string(f.Vector)), orNone(string(f.Encoding))))
	}
	b.WriteString(fmt.Sprintf("- Claim: %s at evidence level %s, attribution %s, basis %s\n",
		f.ClaimType, f.EvidenceLevel, f.AttributionStatus, f.EvidenceBasis))
	b.WriteString(fmt.Sprintf("- **Observed:** %s\n", f.WhatWasObserved))
	b.WriteString(fmt.Sprintf("- **Inferred:** %s\n", f.WhatIsInferred))
	b.WriteString(fmt.Sprintf("- **Missing evidence:** %s\n", f.WhatEvidenceIsMissing))
	b.WriteString("- **Limitations:**\n")
	for _, l := range f.Limitations {
		b.WriteString("  - " + l + "\n")
	}
	b.WriteString(fmt.Sprintf("- Measured impact: %d of %d valid trial(s)%s; population `%s`.\n",
		f.MeasuredImpact.Numerator, f.MeasuredImpact.Denominator, excludedTail(f.MeasuredImpact),
		f.MeasuredImpact.PopulationRef))
	b.WriteString("- Alternatives evaluated:\n")
	for _, a := range f.Alternatives {
		b.WriteString(fmt.Sprintf("  - %s: %s -- %s\n", a.Kind, a.State, a.Justification))
		if a.TestThatWouldResolve != "" {
			b.WriteString(fmt.Sprintf("    - test that would resolve it: %s\n", a.TestThatWouldResolve))
		}
	}
	b.WriteString(fmt.Sprintf("- Recommendation: %s\n", f.Recommendation))
	b.WriteString(fmt.Sprintf("- Priority basis: %s\n", f.PriorityBasis))
	b.WriteString(fmt.Sprintf("- Engineer note: %s\n", f.SecurityEngineerNote))
	b.WriteString(fmt.Sprintf("- Reproduce: `%s`\n", f.ReproductionCommand))
	b.WriteString(fmt.Sprintf("- Regression: `%s`\n", f.RegressionTest))
	if f.HypothesisRef != "" {
		b.WriteString(fmt.Sprintf("- Hypothesis: `%s`\n", f.HypothesisRef))
	}
	// An undetermined area has no C-17 profile by construction, and empty backticks
	// would read as a trail that lost a reference rather than as a zone that never
	// produced one.
	profile := "none: this finding states an absence, so no C-08 profile was compiled"
	if f.EvidenceProfileRef != "" {
		profile = "`" + f.EvidenceProfileRef + "`"
	}
	b.WriteString(fmt.Sprintf("- Evidence profile: %s; observations: %s\n\n", profile,
		orNone(joinLines(f.ObservationRefs, ", "))))
	return b.String()
}

// orNone renders an absent grid coordinate as a dash rather than an empty cell, which
// a reader would otherwise scan as a missing value in a table that is meant to be
// complete.
func orNone(v string) string {
	if v == "" {
		return "-"
	}
	return v
}

func versionsOf(in map[string]string) []string {
	out := make([]string, 0, len(in))
	for id, v := range in {
		out = append(out, fmt.Sprintf("%s=%s", contracts.ID(id).Label()+" ("+id+")", v))
	}
	return sortStrings(out)
}

func utc(t time.Time) string {
	if t.IsZero() {
		return "not stated"
	}
	return t.UTC().Format(time.RFC3339)
}

func joinLines(in []string, sep string) string {
	return strings.Join(in, sep)
}
