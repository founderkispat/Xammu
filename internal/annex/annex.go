// Package annex renders a sealed C-15 report as a client-facing annex.
//
// It is a view, never a second authority: every number and every statement is
// copied from the report argument, and the evidence fields of each finding are
// quoted verbatim from the C-16 record instead of being paraphrased into the
// annex's language. Translation covers the structure, the labels and the
// guidance; it never rewrites what was observed.
package annex

import (
	"fmt"
	"html"
	"strings"
	"time"

	"xammu/internal/contracts"
)

// Lang is the language of the annex's own prose and labels.
type Lang string

const (
	Spanish Lang = "es"
	English Lang = "en"
)

// ParseLang resolves the name an operator types. The empty string means English,
// which is the CLI's default; anything outside the two vocabularies is refused
// rather than guessed.
func ParseLang(name string) (Lang, error) {
	switch strings.ToLower(strings.TrimSpace(name)) {
	case "", "en", "en-us", "en-gb", "english":
		return English, nil
	case "es", "es-es", "es-co", "espa\u00f1ol", "espanol", "spanish":
		return Spanish, nil
	}
	return "", fmt.Errorf("--lang %q is not es or en", name)
}

// Meta is the engagement context the operator supplies. It is printed, never
// stored: the annex is derived on demand from the signed evidence, and the
// bundle keeps no client identity.
type Meta struct {
	Client     string
	Engagement string
	PreparedBy string
}

// Markdown renders the annex as a Markdown document.
func Markdown(rep *contracts.Report, lang Lang, meta Meta) string {
	var b strings.Builder
	newView(rep, lang, meta).write(&mdSink{&b})
	return b.String()
}

// HTML renders the same document as a self-contained HTML page. Both formats
// walk the same view, so a difference between them would be a rendering defect
// rather than two sets of claims.
func HTML(rep *contracts.Report, lang Lang, meta Meta) string {
	var b strings.Builder
	b.WriteString("<!doctype html>\n<html lang=\"")
	b.WriteString(html.EscapeString(string(lang)))
	b.WriteString("\">\n<head>\n<meta charset=\"utf-8\">\n<title>")
	b.WriteString(html.EscapeString(pick(lang, "Anexo técnico - XAMMU", "Technical annex - XAMMU")))
	b.WriteString("</title>\n<style>\n")
	b.WriteString("body{font-family:system-ui,-apple-system,'Segoe UI',sans-serif;max-width:960px;margin:2rem auto;padding:0 1rem;line-height:1.55;color:#111}")
	b.WriteString("table{border-collapse:collapse;width:100%;margin:1rem 0;font-size:.9rem}")
	b.WriteString("th,td{border:1px solid #ccc;padding:.35rem .5rem;text-align:left;vertical-align:top}")
	b.WriteString("th{background:#f2f2f2}code{background:#f5f5f5;padding:.1rem .3rem}")
	b.WriteString("pre{background:#f5f5f5;padding:.75rem;overflow:auto}h2{margin-top:2rem;border-bottom:1px solid #ddd}")
	b.WriteString("</style>\n</head>\n<body>\n")
	newView(rep, lang, meta).write(&htmlSink{&b})
	b.WriteString("\n</body>\n</html>\n")
	return b.String()
}

type view struct {
	rep  *contracts.Report
	lang Lang
	meta Meta
}

func newView(rep *contracts.Report, lang Lang, meta Meta) *view {
	return &view{rep: rep, lang: lang, meta: meta}
}

func (v *view) t(es, en string) string { return pick(v.lang, es, en) }

func pick(lang Lang, es, en string) string {
	if lang == Spanish {
		return es
	}
	return en
}

func (v *view) write(s sink) {
	s.h1(v.t("Anexo técnico - Perfilado de comportamiento defensivo del borde",
		"Technical annex - Defensive edge behaviour profiling"))
	s.p(v.t("Documento generado por XAMMU a partir de un bundle de evidencia sellado. "+
		"Se anexa al informe de auditoría y no lo sustituye.",
		"Generated by XAMMU from a sealed evidence bundle. It is annexed to the audit "+
			"report and does not replace it."))

	v.writeMeta(s)
	v.writeNature(s)
	v.writeSummary(s)
	v.writeMatrix(s)
	v.writeFindings(s)
	v.writeZones(s)
	v.writeRisk(s)
	v.writeEvidence(s)
	v.writeLimits(s)
	v.writeOutOfScope(s)
}

func (v *view) writeMeta(s sink) {
	s.h2(v.t("1. Datos del engagement", "1. Engagement data"))
	meta := v.meta
	rows := [][]string{
		{v.t("Cliente", "Client"), orStated(meta.Client, v.lang)},
		{v.t("Engagement", "Engagement"), orStated(meta.Engagement, v.lang)},
		{v.t("Preparado por", "Prepared by"), orStated(meta.PreparedBy, v.lang)},
		{v.t("Run", "Run"), v.rep.RunID},
		{v.t("Objetivo medido", "Measured target"), v.rep.TargetOrigin},
		{v.t("Autorización", "Authorization"), v.rep.AuthorizationRef},
		{v.t("Autorización válida hasta", "Authorization valid until"), utc(v.rep.AuthorizationValidUntil, v.lang)},
		{v.t("Generado", "Generated"), v.rep.GeneratedAt.UTC().Format(time.RFC3339)},
		{v.t("Duración", "Duration"), fmt.Sprintf("%d s", v.rep.DurationSeconds)},
		{v.t("Presupuesto", "Budget"), fmt.Sprintf("%d / %d", v.rep.RequestsUsed, v.rep.RequestBudget)},
		{v.t("Partición del corpus", "Corpus partition"), v.rep.Partition},
		{v.t("Estado del run", "Run state"), stateLabel(v.rep.RunState, v.lang)},
		{v.t("Esquema", "Schema"), v.rep.SchemaVersion},
		{v.t("Herramienta", "Tool"), v.rep.Evidence.ToolVersion},
	}
	s.table([]string{v.t("Campo", "Field"), v.t("Valor", "Value")}, rows)
	if v.rep.StateReason != "" {
		s.p(v.t("Motivo del estado: ", "State reason: ") + v.rep.StateReason)
	}
}

func (v *view) writeNature(s sink) {
	s.h2(v.t("2. Qué mide este anexo y qué no", "2. What this annex measures and what it does not"))
	s.p(v.t(
		"XAMMU mide cómo un borde defensivo (WAF, proxy o front end) trata solicitudes "+
			"concretas. Las sondas son inertes y llevan una marca diagnóstica: no ejecutan "+
			"código, no explotan nada y no evalúan la aplicación.",
		"XAMMU measures how a defensive edge (WAF, proxy or front end) handles specific "+
			"requests. The probes are inert and carry a diagnostic marker: they execute no "+
			"code, exploit nothing and do not evaluate the application."))
	s.p(v.t(
		"El anexo describe comportamiento observado y lo que la evidencia permite inferir. "+
			"No certifica que el WAF sea seguro, no sustituye una prueba de penetración y no "+
			"autoriza a afirmar que la aplicación tenga una vulnerabilidad.",
		"The annex describes observed behaviour and what the evidence supports inferring. It "+
			"does not attest that the WAF is secure, does not replace a penetration test and "+
			"does not license a claim that the application is vulnerable."))
	s.p(v.t(
		"Una ejecución mide un objetivo. La evidencia se sella con una cadena de hashes y una "+
			"firma; el comando de la sección 8 permite comprobar que no fue alterada.",
		"One run measures one target. The evidence is sealed with a hash chain and a "+
			"signature; the command in section 8 shows it was not altered."))
	if v.lang == Spanish {
		s.p("Los campos de evidencia de cada hallazgo y las declaraciones que provienen del " +
			"informe sellado se citan verbatim (en inglés) para no alterar su significado. " +
			"Los títulos, el resumen y las indicaciones de este anexo están en español.")
	} else {
		s.p("Every evidence field and every statement copied from the sealed report is quoted " +
			"verbatim; this document does not paraphrase it.")
	}
}

func (v *view) writeSummary(s sink) {
	s.h2(v.t("3. Resultado en una vista", "3. Result at a glance"))
	counts := map[contracts.FindingType]int{}
	for _, f := range v.rep.Findings {
		counts[f.FindingType]++
	}
	var bullets []string
	for _, t := range contracts.AllFindingTypes() {
		bullets = append(bullets, fmt.Sprintf("%s (`%s`): %d", findingTypeLabel(t, v.lang), t, counts[t]))
	}
	bullets = append(bullets,
		fmt.Sprintf("%s: %d", v.t("Hallazgos publicados", "Published findings"), len(v.rep.Findings)),
		fmt.Sprintf("%s: %d / %d", v.t("Celdas planificadas con lectura",
			"Planned cells with a reading"),
			v.measuredCells(), len(v.rep.Matrix.Cells)),
		fmt.Sprintf("%s: %d", v.t("Zonas no evaluadas", "Unevaluated zones"), len(v.rep.Unevaluated)),
		fmt.Sprintf("%s: %d / %d", v.t("Solicitudes usadas", "Requests used"),
			v.rep.RequestsUsed, v.rep.RequestBudget),
	)
	s.bullets(bullets)
	s.p(v.t("Ninguna cifra de este anexo es una estimación: todas se copian del informe C-15 "+
		"derivado de la evidencia sellada.",
		"No figure in this annex is an estimate: every one is copied from the C-15 report "+
			"derived from the sealed evidence."))
}

func (v *view) measuredCells() int {
	n := 0
	for _, c := range v.rep.Matrix.Cells {
		if c.Status == "measured" || c.Status == "partial" {
			n++
		}
	}
	return n
}

func (v *view) writeMatrix(s sink) {
	s.h2(v.t("4. Matriz de cobertura clase x vector", "4. Coverage matrix: class x vector"))
	if v.rep.Matrix.Basis != "" {
		s.p(v.t("Base: ", "Basis: ") + v.rep.Matrix.Basis)
	}
	var rows [][]string
	for _, c := range v.rep.Matrix.Cells {
		if len(c.Encodings) == 0 {
			rows = append(rows, []string{
				classLabel(c.Class, v.lang), vectorLabel(c.Vector, v.lang),
				"-", statusLabel(c.Status, v.lang),
				fmt.Sprint(c.Aggregate.Numerator), fmt.Sprint(c.Aggregate.Denominator),
				"-", "-", "-", "-", claimLabel(c.ClaimType, v.lang), levelLabel(c.Evidence, v.lang),
			})
			continue
		}
		for _, e := range c.Encodings {
			rows = append(rows, []string{
				classLabel(c.Class, v.lang), vectorLabel(c.Vector, v.lang),
				encodingLabel(e.Encoding, v.lang), statusLabel(c.Status, v.lang),
				fmt.Sprint(e.ValidTrials), fmt.Sprint(e.Blocked), fmt.Sprint(e.Passed),
				fmt.Sprint(e.Inconclusive), yesNo(e.ControlValid, v.lang),
				verdictLabel(e.Verdict, v.lang), claimLabel(c.ClaimType, v.lang),
				levelLabel(e.Evidence, v.lang),
			})
		}
	}
	if len(rows) == 0 {
		s.p(v.t("No se midió ninguna celda en esta ejecución.", "No cell was measured in this run."))
	} else {
		s.table([]string{
			v.t("Clase", "Class"), v.t("Vector", "Vector"), v.t("Codificación", "Encoding"),
			v.t("Estado", "Status"), v.t("Válidas", "Valid"), v.t("Bloqueadas", "Blocked"),
			v.t("Pasan", "Passed"), v.t("Inconclusas", "Inconclusive"),
			v.t("Control", "Control"), v.t("Veredicto", "Verdict"),
			v.t("Afirmación", "Claim"), v.t("Evidencia", "Evidence"),
		}, rows)
	}

	s.h3(v.t("Huecos declarados", "Declared holes"))
	if len(v.rep.Matrix.NotMeasured) == 0 {
		s.bullets([]string{v.t("Ninguno.", "None.")})
		return
	}
	s.bullets(v.rep.Matrix.NotMeasured)
}

func (v *view) writeFindings(s sink) {
	s.h2(v.t("5. Hallazgos", "5. Findings"))
	if len(v.rep.Findings) == 0 {
		s.p(v.t("No se publicó ningún hallazgo en esta ejecución.",
			"No finding was published in this run."))
		return
	}
	for _, f := range v.rep.Findings {
		s.h3(fmt.Sprintf("%s - %s", f.Ref, findingTypeLabel(f.FindingType, v.lang)))
		rows := [][]string{
			{v.t("Tipo", "Type"), fmt.Sprintf("%s (`%s`)", findingTypeLabel(f.FindingType, v.lang), f.FindingType)},
			{v.t("Prioridad", "Priority"), fmt.Sprintf("%s (`%s`)", priorityLabel(f.Priority, v.lang), f.Priority)},
			{v.t("Base de la prioridad", "Priority basis"), f.PriorityBasis},
			{v.t("Alcance afectado", "Affected scope"), f.AffectedScope},
		}
		if f.AttackClass != "" || f.Vector != "" || f.Encoding != "" {
			rows = append(rows, []string{
				v.t("Posición en la matriz", "Grid position"),
				fmt.Sprintf("%s / %s / %s", classLabel(f.AttackClass, v.lang),
					vectorLabel(f.Vector, v.lang), encodingLabel(f.Encoding, v.lang)),
			})
		}
		rows = append(rows,
			[]string{v.t("Afirmación", "Claim"), fmt.Sprintf("%s (%s); %s (%s); %s (%s)",
				claimLabel(f.ClaimType, v.lang), f.ClaimType,
				levelLabel(f.EvidenceLevel, v.lang), f.EvidenceLevel,
				attributionLabel(f.AttributionStatus, v.lang), f.AttributionStatus)},
			[]string{v.t("Impacto medido", "Measured impact"), fmt.Sprintf("%d / %d %s; %s",
				f.MeasuredImpact.Numerator, f.MeasuredImpact.Denominator,
				v.t("pruebas válidas", "valid trials"), f.MeasuredImpact.Basis)},
			[]string{v.t("Recomendación", "Recommendation"), f.Recommendation},
			[]string{v.t("Nota para el ingeniero", "Security engineer note"), f.SecurityEngineerNote},
		)
		if f.UnevaluatedReason != "" {
			rows = append(rows, []string{v.t("Motivo tipado", "Typed reason"),
				fmt.Sprintf("%s (`%s`)", reasonLabel(f.UnevaluatedReason, v.lang), f.UnevaluatedReason)})
		}
		s.table([]string{v.t("Campo", "Field"), v.t("Valor", "Value")}, rows)

		s.bullets([]string{
			"**" + v.t("Observado", "Observed") + ":** " + f.WhatWasObserved,
			"**" + v.t("Inferido", "Inferred") + ":** " + f.WhatIsInferred,
			"**" + v.t("Evidencia faltante", "Missing evidence") + ":** " + f.WhatEvidenceIsMissing,
		})
		var limits []string
		for _, l := range f.Limitations {
			limits = append(limits, "**"+v.t("Limitación", "Limitation")+":** "+l)
		}
		if len(limits) > 0 {
			s.bullets(limits)
		}
		if len(f.Alternatives) > 0 {
			var alts []string
			for _, a := range f.Alternatives {
				line := fmt.Sprintf("%s (`%s`), %s: %s", alternativeKindLabel(a.Kind, v.lang), a.Kind,
					alternativeStateLabel(a.State, v.lang), a.Justification)
				if a.TestThatWouldResolve != "" {
					line += " — " + v.t("Prueba que lo resolvería: ", "Test that would resolve it: ") +
						a.TestThatWouldResolve
				}
				alts = append(alts, line)
			}
			s.p(v.t("Alternativas evaluadas:", "Alternatives evaluated:"))
			s.bullets(alts)
		}
		s.p(v.t("Reproducir:", "Reproduce:"))
		s.code(f.ReproductionCommand)
		s.p(v.t("Prueba de regresión:", "Regression test:"))
		s.code(f.RegressionTest)
		if f.EvidenceProfileRef != "" {
			s.p(v.t("Perfil de evidencia: ", "Evidence profile: ") + f.EvidenceProfileRef +
				v.t("; observaciones: ", "; observations: ") + strings.Join(f.ObservationRefs, ", "))
		}
	}
}

func (v *view) writeZones(s sink) {
	s.h2(v.t("6. Zonas no evaluadas", "6. Unevaluated zones"))
	if len(v.rep.Unevaluated) == 0 {
		if v.rep.UnevaluatedNone {
			s.p(v.t("La ejecución declara esta sección vacía: toda zona registrada aparece en los "+
				"hallazgos y no quedó nada sin leer.",
				"The run declares this section empty: every recorded zone is in the findings and "+
					"nothing else was left unread."))
			return
		}
		s.p(v.t("No se registraron zonas no evaluadas.", "No unevaluated zone was recorded."))
		return
	}
	for _, z := range v.rep.Unevaluated {
		s.h3(z.Scope)
		s.table([]string{v.t("Campo", "Field"), v.t("Valor", "Value")}, [][]string{
			{v.t("Motivo", "Reason"), fmt.Sprintf("%s (`%s`)", reasonLabel(z.Reason, v.lang), z.Reason)},
			{v.t("Detalle", "Detail"), z.Detail},
			{v.t("Remediación", "Remediation"), z.Remediation},
			{v.t("Solicitudes planificadas no gastadas", "Planned requests not spent"), fmt.Sprint(z.PlannedRequests)},
		})
		s.p(v.t("Reproducir:", "Reproduce:"))
		s.code(z.ReproductionCommand)
	}
}

func (v *view) writeRisk(s sink) {
	s.h2(v.t("7. Riesgo residual: tres escenarios separados",
		"7. Residual risk: three statements kept apart"))
	v.scenario(s, v.t("Riesgo condicional", "Conditional risk"), v.rep.ResidualRisk.ConditionalRisk)
	v.scenario(s, v.t("Condición no demostrada", "Condition not demonstrated"),
		v.rep.ResidualRisk.ConditionNotDemonstrated)
	v.scenario(s, v.t("No determinable", "Undeterminable"), v.rep.ResidualRisk.Undeterminable)
}

func (v *view) scenario(s sink, heading string, sc contracts.Scenario) {
	s.h3(heading)
	s.table([]string{v.t("Campo", "Field"), v.t("Valor", "Value")}, [][]string{
		{v.t("Declaración", "Statement"), sc.Statement},
		{v.t("Alcance", "Scope"), sc.Scope},
	})
	if len(sc.Untested) > 0 {
		s.p(v.t("No probado:", "Not tested:"))
		s.bullets(sc.Untested)
	}
	if sc.Verification != "" {
		s.p(v.t("Verificación:", "Verification:"))
		s.code(sc.Verification)
	}
}

func (v *view) writeEvidence(s sink) {
	s.h2(v.t("8. Evidencia y reproducibilidad", "8. Evidence and reproducibility"))
	e := v.rep.Evidence
	s.bullets([]string{
		fmt.Sprintf("%s: `%s`", v.t("Manifiesto", "Manifest"), e.ManifestPath),
		fmt.Sprintf("%s: `%s`", v.t("Digest del manifiesto", "Manifest digest"), e.ManifestDigest),
		fmt.Sprintf("%s: %d", v.t("Observaciones", "Observations"), e.ObservationCount),
		fmt.Sprintf("%s: %s", v.t("Rondas", "Rounds"), strings.Join(e.RoundIDs, ", ")),
		fmt.Sprintf("%s: `%s`", v.t("Corpus", "Corpus"), e.CorpusCommitRef),
		fmt.Sprintf("%s: `%s`", v.t("Conjunto de detectores", "Detector set"), e.DetectorSetHash),
		fmt.Sprintf("%s: `%s`", v.t("Generado por", "Generated by"), e.GeneratedByUser),
	})
	s.p(v.t("Verificar la evidencia:", "Verify the evidence:"))
	s.code(e.VerifyCommand)
	s.p(v.t(
		"El comando comprueba que el manifiesto satisface su contrato, que la firma es válida, "+
			"que el inventario coincide con el disco, que el Merkle root recomputa y que la "+
			"cadena de hashes no tiene cortes. No demuestra que las lecturas sean correctas y, "+
			"sin una clave de confianza obtenida por un canal independiente, no prueba quién firmó.",
		"The command checks that the manifest satisfies its contract, that the signature is "+
			"valid, that the inventory matches the disk, that the Merkle root recomputes and that "+
			"the hash chain has no breaks. It does not prove the readings are correct and, without "+
			"a trusted key obtained through an independent channel, it does not prove who signed."))
}

