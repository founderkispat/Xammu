func (v *view) writeOutOfScope(s sink) {
	s.h2(v.t("10. Declarado fuera de alcance", "10. Declared out of scope"))
	if len(v.rep.OutOfScope) == 0 {
		s.p(v.t("La ejecución no declaró exclusiones adicionales.",
			"The run declared no additional exclusions."))
		return
	}
	var bullets []string
	for _, code := range v.rep.OutOfScope {
		text := outOfScopeEN[code]
		if v.lang == Spanish {
			text = outOfScopeES[code]
		}
		if text == "" {
			text = code
		}
		bullets = append(bullets, fmt.Sprintf("%s (`%s`)", text, code))
	}
	s.bullets(bullets)
}

// --- sinks -----------------------------------------------------------------

type sink interface {
	h1(string)
	h2(string)
	h3(string)
	p(string)
	bullets([]string)
	table(header []string, rows [][]string)
	code(string)
}

type mdSink struct{ b *strings.Builder }

func (m *mdSink) h1(text string) { fmt.Fprintf(m.b, "# %s\n\n", oneLine(text)) }
func (m *mdSink) h2(text string) { fmt.Fprintf(m.b, "\n## %s\n\n", oneLine(text)) }
func (m *mdSink) h3(text string) { fmt.Fprintf(m.b, "\n### %s\n\n", oneLine(text)) }
func (m *mdSink) p(text string)  { fmt.Fprintf(m.b, "%s\n\n", oneLine(text)) }
func (m *mdSink) bullets(items []string) {
	for _, it := range items {
		fmt.Fprintf(m.b, "- %s\n", oneLine(it))
	}
	m.b.WriteString("\n")
}
func (m *mdSink) table(header []string, rows [][]string) {
	writeRow := func(cells []string) {
		m.b.WriteString("| ")
		for i, c := range cells {
			if i > 0 {
				m.b.WriteString(" | ")
			}
			m.b.WriteString(mdCell(c))
		}
		m.b.WriteString(" |\n")
	}
	writeRow(header)
	for range header {
		m.b.WriteString("| --- ")
	}
	m.b.WriteString("|\n")
	for _, row := range rows {
		writeRow(row)
	}
	m.b.WriteString("\n")
}
func (m *mdSink) code(text string) { fmt.Fprintf(m.b, "```\n%s\n```\n\n", strings.TrimSpace(text)) }

type htmlSink struct{ b *strings.Builder }

func (h *htmlSink) h1(text string) {
	fmt.Fprintf(h.b, "<h1>%s</h1>\n", html.EscapeString(oneLine(text)))
}
func (h *htmlSink) h2(text string) {
	fmt.Fprintf(h.b, "<h2>%s</h2>\n", html.EscapeString(oneLine(text)))
}
func (h *htmlSink) h3(text string) {
	fmt.Fprintf(h.b, "<h3>%s</h3>\n", html.EscapeString(oneLine(text)))
}
func (h *htmlSink) p(text string) { fmt.Fprintf(h.b, "<p>%s</p>\n", html.EscapeString(oneLine(text))) }
func (h *htmlSink) bullets(items []string) {
	h.b.WriteString("<ul>\n")
	for _, it := range items {
		fmt.Fprintf(h.b, "<li>%s</li>\n", html.EscapeString(oneLine(it)))
	}
	h.b.WriteString("</ul>\n")
}
func (h *htmlSink) table(header []string, rows [][]string) {
	h.b.WriteString("<table>\n<thead><tr>")
	for _, cell := range header {
		fmt.Fprintf(h.b, "<th>%s</th>", html.EscapeString(oneLine(cell)))
	}
	h.b.WriteString("</tr></thead>\n<tbody>\n")
	for _, row := range rows {
		h.b.WriteString("<tr>")
		for _, cell := range row {
			fmt.Fprintf(h.b, "<td>%s</td>", html.EscapeString(oneLine(cell)))
		}
		h.b.WriteString("</tr>\n")
	}
	h.b.WriteString("</tbody>\n</table>\n")
}
func (h *htmlSink) code(text string) {
	fmt.Fprintf(h.b, "<pre><code>%s</code></pre>\n", html.EscapeString(strings.TrimSpace(text)))
}

