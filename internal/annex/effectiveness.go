// EffectivenessMarkdown renders one xammu.gate/v1 document as a client-facing
// annex in Spanish or English. It is the same kind of document as Markdown: a
// view over a signed/derived record, never a second authority. Labels and prose
// are translated; every figure and every C-16 evidence field is copied from the
// gate document unchanged.
func EffectivenessMarkdown(doc *gate.Document, lang Lang, meta Meta, publicationDir string) string {
	var b strings.Builder
	newEffectivenessView(doc, lang, meta, publicationDir).write(&mdSink{&b})
	return b.String()
}

type effectivenessView struct {
	doc            *gate.Document
	lang           Lang
	meta           Meta
	publicationDir string
}

func newEffectivenessView(doc *gate.Document, lang Lang, meta Meta, publicationDir string) *effectivenessView {
	return &effectivenessView{doc: doc, lang: lang, meta: meta, publicationDir: publicationDir}
}

func (v *effectivenessView) t(es, en string) string { return pick(v.lang, es, en) }

func (v *effectivenessView) write(s sink) {
	d := v.doc
	s.h1(v.t("Anexo técnico - Eficacia del borde defensivo",
		"Technical annex - Defensive edge effectiveness"))
	s.p(v.t("Documento generado por XAMMU a partir de un bundle de evidencia sellado. Copia las "+
		"cifras y los campos de evidencia del documento de gate; no los recalcula.",
		"Generated by XAMMU from a sealed evidence bundle. It copies the figures and evidence "+
			"fields of the gate document; it does not recompute them."))
	s.p(v.t("Run: ", "Run: ") + d.Source.RunID + v.t(". Bundle: ", ". Bundle: ") + d.Source.Bundle)

	v.writeMeta(s)
	v.writeVerdict(s)
	v.writeMetrics(s)
	v.writeControls(s)
	v.writeFindings(s)
	v.writeLimits(s)
	v.writeSeal(s)
}

func (v *effectivenessView) writeMeta(s sink) {
	d := v.doc
	s.h2(v.t("1. Datos del engagement", "1. Engagement data"))
	m := d.Metrics
	rows := [][]string{
		{v.t("Cliente", "Client"), orStated(v.meta.Client, v.lang)},
		{v.t("Engagement", "Engagement"), orStated(v.meta.Engagement, v.lang)},
		{v.t("Preparado por", "Prepared by"), orStated(v.meta.PreparedBy, v.lang)},
		{v.t("Run", "Run"), d.Source.RunID},
		{v.t("Tipo de fuente", "Source kind"), d.Source.Kind},
		{v.t("Bundle", "Bundle"), d.Source.Bundle},
		{v.t("Digest del manifiesto", "Manifest digest"), d.Source.ManifestSHA256},
		{v.t("Clave firmante del manifiesto", "Manifest signer key"), d.Source.ManifestSignerKeyID},
		{v.t("Política (sha256)", "Policy (sha256)"), d.Policy.SHA256},
		{v.t("Esquema del documento", "Document schema"), d.SchemaVersion},
		{v.t("Herramienta", "Tool"), d.ToolVersion},
	}
	if m != nil {
		rows = append(rows,
			[]string{v.t("Autorización", "Authorization"), m.AuthorizationRef},
			[]string{v.t("Digest del corpus", "Corpus digest"), m.CorpusDigest},
			[]string{v.t("Casos medidos", "Cases measured"), fmt.Sprint(m.Cases)},
		)
	}
	s.table([]string{v.t("Campo", "Field"), v.t("Valor", "Value")}, rows)
}

func (v *effectivenessView) writeVerdict(s sink) {
	d := v.doc
	s.h2(v.t("2. Veredicto", "2. Verdict"))
	verdict := v.t("no cumple", "fail")
	if d.Verdict == gate.VerdictPass {
		verdict = v.t("cumple", "pass")
	}
	s.bullets([]string{
		fmt.Sprintf("%s: **%s** (`%s`)", v.t("Veredicto", "Verdict"), verdict, d.Verdict),
		v.t("El veredicto es una decisión de política sobre los umbrales configurados para este "+
			"corpus y este origen; no es una afirmación de seguridad general.",
			"The verdict is a policy decision over the thresholds configured for this corpus and "+
				"this origin; it is not a general security assertion."),
	})
}

func (v *effectivenessView) writeMetrics(s sink) {
	d := v.doc
	s.h2(v.t("3. Métricas", "3. Metrics"))
	m := d.Metrics
	if m == nil {
		s.p(v.t("Este bundle contiene hallazgos de perfilado y no métricas de eficacia E-03.",
			"This bundle carries profiling findings and no E-03 effectiveness metrics."))
		return
	}
	s.h3(v.t("Matriz de confusión", "Confusion matrix"))
	s.table([]string{"TP", "FN", "FP", "TN", v.t("Excluidas", "Excluded"), v.t("Casos", "Cases")},
		[][]string{{
			fmt.Sprint(m.Counts.TP), fmt.Sprint(m.Counts.FN), fmt.Sprint(m.Counts.FP),
			fmt.Sprint(m.Counts.TN), fmt.Sprint(m.Counts.Excluded), fmt.Sprint(m.Cases),
		}})
	s.p(v.t("Las pruebas excluidas se informan al lado de la matriz y nunca dentro de un "+
		"denominador. Una tasa nula significa que el denominador era cero.",
		"Excluded exchanges are reported beside the matrix and never inside a denominator. A null "+
			"rate means the denominator was zero."))

	s.h3(v.t("Tasas", "Rates"))
	s.table([]string{v.t("Métrica", "Metric"), v.t("Valor", "Value")}, [][]string{
		{"TPR", effRate(m.Rates.TPR)},
		{"FPR", effRate(m.Rates.FPR)},
		{v.t("Precisión", "Precision"), effRate(m.Rates.Precision)},
		{"F1", effRate(m.Rates.F1)},
		{"MCC", effRate(m.Rates.MCC)},
	})

	keys := make([]string, 0, len(m.Classes))
	for k := range m.Classes {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	s.h3(v.t("Por clase", "By class"))
	rows := make([][]string, 0, len(keys))
	for _, k := range keys {
		c := m.Classes[k]
		rows = append(rows, []string{
			classLabel(contracts.AttackClass(c.Class), v.lang), fmt.Sprint(c.Counts.TP),
			fmt.Sprint(c.Counts.FN), fmt.Sprint(c.Counts.FP), fmt.Sprint(c.Counts.TN),
			effRate(c.Rates.TPR), effRate(c.Rates.FPR), effRate(c.Rates.Precision), c.OWASP,
		})
	}
	s.table([]string{v.t("Clase", "Class"), "TP", "FN", "FP", "TN", "TPR", "FPR",
		v.t("Precisión", "Precision"), "OWASP"}, rows)

	s.h3(v.t("Latencias", "Latency"))
	s.table([]string{v.t("Población", "Population"), "n", "p50 ms", "p95 ms", "p99 ms",
		v.t("Suficiencia", "Sufficiency")}, [][]string{{
		v.t("intercambios concluyentes", "conclusive exchanges"), fmt.Sprint(m.Latency.N),
		effMillis(m.Latency.P50), effMillis(m.Latency.P95), effMillis(m.Latency.P99),
		sampleNote(m.Latency.SufficientSample, m.Latency.P99Sufficient, v.lang),
	}})

	if len(m.Arms) > 0 {
		s.h3(v.t("Brazos", "Arms"))
		names := make([]string, 0, len(m.Arms))
		for k := range m.Arms {
			names = append(names, k)
		}
		sort.Strings(names)
		rows = rows[:0]
		for _, name := range names {
			a := m.Arms[name]
			stack := v.t("ninguno", "none")
			if len(a.TamperStack) > 0 {
				stack = strings.Join(a.TamperStack, "+")
			}
			rows = append(rows, []string{name, stack, fmt.Sprint(a.Cases), effRate(a.Rates.TPR),
				effRate(a.Rates.FPR), effRate(a.Rates.Precision), fmt.Sprint(a.Latency.N)})
		}
		s.table([]string{v.t("Brazo", "Arm"), v.t("Pila de tamper", "Tamper stack"),
			v.t("Casos", "Cases"), "TPR", "FPR", v.t("Precisión", "Precision"), "n"}, rows)
	}
	if len(m.Comparison) > 0 {
		s.h3(v.t("Base frente a tamper", "Baseline vs tamper"))
		names := make([]string, 0, len(m.Comparison))
		for k := range m.Comparison {
			names = append(names, k)
		}
		sort.Strings(names)
		rows = rows[:0]
		for _, name := range names {
			c := m.Comparison[name]
			rows = append(rows, []string{
				classLabel(contracts.AttackClass(c.Class), v.lang), effPct(c.BaselineTPR),
				fmt.Sprint(c.BaselineN), effPct(c.TamperTPR), fmt.Sprint(c.TamperN),
				effDelta(c.DeltaPP), c.Note,
			})
		}
		s.table([]string{v.t("Clase", "Class"), "TPR base", "n base", "TPR tamper", "n tamper",
			"Delta", v.t("Nota", "Note")}, rows)
	}
}

func (v *effectivenessView) writeControls(s sink) {
	d := v.doc
	s.h2(v.t("4. Controles con evidencia", "4. Controls with evidence"))
	keys := make([]string, 0, len(d.Controls))
	for k := range d.Controls {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	rows := make([][]string, 0, len(keys))
	for _, id := range keys {
		c := d.Controls[id]
		rows = append(rows, []string{id, c.Expectation, c.Observed, c.Evidence,
			gateStatusLabel(c.Status, v.lang)})
	}
	s.table([]string{v.t("Control", "Control"), v.t("Expectativa", "Expectation"),
		v.t("Observado", "Observed"), v.t("Evidencia", "Evidence"), v.t("Estado", "Status")}, rows)
	if len(d.NotApplicable) > 0 {
		s.h3(v.t("Controles no aplicables", "Checks that did not apply"))
		keys = keys[:0]
		for k := range d.NotApplicable {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		rows = rows[:0]
		for _, id := range keys {
			rows = append(rows, []string{id, d.NotApplicable[id]})
		}
		s.table([]string{v.t("Control", "Check"), v.t("Motivo", "Reason")}, rows)
	}
}

func (v *effectivenessView) writeFindings(s sink) {
	d := v.doc
	s.h2(v.t("5. Hallazgos C-16 sellados", "5. Sealed C-16 findings"))
	if len(d.Findings) == 0 {
		s.p(v.t("Este bundle no publica hallazgos C-16.",
			"This bundle publishes no C-16 finding."))
		return
	}
	keys := make([]string, 0, len(d.Findings))
	for k := range d.Findings {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, ref := range keys {
		f := d.Findings[ref]
		s.h3(fmt.Sprintf("%s - %s (%s)", ref, f.FindingType, f.Priority))
		s.table([]string{v.t("Campo", "Field"), v.t("Valor", "Value")}, [][]string{
			{v.t("Prioridad", "Priority"), fmt.Sprintf("%s (`%s`); %s", priorityLabel(
				contracts.Priority(f.Priority), v.lang), f.Priority, f.PriorityBasis)},
			{v.t("Alcance afectado", "Affected scope"), f.AffectedScope},
			{v.t("Impacto medido", "Measured impact"), fmt.Sprintf("%d/%d (%s)",
				f.MeasuredImpact.Numerator, f.MeasuredImpact.Denominator, f.MeasuredImpact.Basis)},
		})
		s.bullets([]string{
			"**" + v.t("Observado", "Observed") + ":** " + f.WhatWasObserved,
			"**" + v.t("Inferido", "Inferred") + ":** " + f.WhatIsInferred,
			"**" + v.t("Evidencia faltante", "Missing evidence") + ":** " + f.WhatEvidenceIsMissing,
		})
		if len(f.Limitations) > 0 {
			s.p(v.t("Limitaciones:", "Limitations:"))
			s.bullets(f.Limitations)
		}
		if f.ReproductionCommand != "" {
			s.p(v.t("Reproducir:", "Reproduce:"))
			s.code(f.ReproductionCommand)
		}
	}
}

func (v *effectivenessView) writeLimits(s sink) {
	s.h2(v.t("6. Límites explícitos", "6. Explicit limits"))
	s.bullets(v.doc.Limits)
}

func (v *effectivenessView) writeSeal(s sink) {
	d := v.doc
	s.h2(v.t("7. Reproducción y sello", "7. Reproduction and seal"))
	dir := v.publicationDir
	if dir == "" {
		dir = "DIR"
	}
	s.p(v.t("Verificar la evidencia sellada:", "Verify the sealed evidence:"))
	s.code("xammu verify --store " + d.Source.Bundle)
	s.p(v.t("Verificar esta entrega y su sobre Ed25519:",
		"Verify this delivery and its Ed25519 envelope:"))
	s.code("xammu verify --publication " + dir + " --trust-key FILE")
	s.p(v.t("El sobre `publication.json` ("+gate.PublicationSchemaVersion+") firma con Ed25519 "+
		"sobre sha256(canonical-json(publication sin los campos de firma)). Lista cada archivo "+
		"entregado con su sha256, incluido este anexo. Un documento no puede contener el digest "+
		"del sobre que lo hashea: `verify --publication` lo recomputa, lo imprime y rechaza "+
		"cualquier archivo que ya no coincida.",
		"The `publication.json` envelope ("+gate.PublicationSchemaVersion+") signs with Ed25519 over "+
			"sha256(canonical-json(publication minus the signature fields)). It lists every "+
			"delivered file with its sha256, including this annex. A document cannot contain the "+
			"digest of the envelope that hashes it: `verify --publication` recomputes it, prints "+
			"it and refuses any file that no longer matches."))
}

// --- helpers ---------------------------------------------------------------

func gateStatusLabel(v string, lang Lang) string {
	switch v {
	case gate.StatusPass:
		return pick(lang, "cumple", "pass")
	case gate.StatusFail:
		return pick(lang, "falla", "fail")
	case gate.StatusNotApplicable:
		return pick(lang, "no aplicable", "not applicable")
	case gate.StatusInfo:
		return pick(lang, "informativo", "informational")
	}
	return v
}

func effRate(v *float64) string {
	if v == nil {
		return "n/a"
	}
	return fmt.Sprintf("%s (%.2f%%)", fmt.Sprintf("%g", *v), *v*100)
}

func effPct(v *float64) string {
	if v == nil {
		return "n/a"
	}
	return fmt.Sprintf("%.2f%%", *v*100)
}

func effDelta(v *float64) string {
	if v == nil {
		return "n/a"
	}
	if *v > 0 {
		return fmt.Sprintf("+%.2f pp", *v)
	}
	return fmt.Sprintf("%.2f pp", *v)
}

func effMillis(v float64) string { return fmt.Sprintf("%.2f", v) }

func sampleNote(sufficient, p99 bool, lang Lang) string {
	switch {
	case sufficient && p99:
		return pick(lang, "n>=100, p99 estable", "n>=100, p99 stable")
	case sufficient:
		return pick(lang, "n>=20, p99 describe menos de 100 intercambios",
			"n>=20, p99 describes fewer than 100 exchanges")
	default:
		return pick(lang, "n<20, las colas describen pocos intercambios",
			"n<20, tail figures describe a handful of exchanges")
	}
}
