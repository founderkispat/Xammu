// The laboratory origin routes one path, so a benign path case is only
// conclusive against that route. The population carries a single path case and
// keeps the count with query traffic, which the origin does answer: a case that
// can only return 404 would measure the missing route, not the WAF.
var benignPaths = []string{"search"}

func buildBenign() []entry {
	var out []entry
	add := func(id, class, payload, vector, encoding, parameter, method, path, provenance, rationale string) {
		out = append(out, entry{
			ID: id, Kind: "benign", Class: class, Payload: payload, Vector: vector,
			Encoding: encoding, Parameter: parameter, Method: method, Path: path,
			Expect: "allowed", Provenance: provenance, Rationale: rationale,
		})
	}
	for i, t := range textExcerpts {
		add(fmt.Sprintf("benign-text-%03d", i+1), "benign_text", t.text, "query", "canonical",
			"q", "GET", "", "public domain: "+t.source,
			"Public-domain prose used as a legitimate search query; some contain apostrophes and "+
				"punctuation that a naive quote rule can over-block.")
	}
	for i, body := range jsonBodies {
		add(fmt.Sprintf("benign-json-%03d", i+1), "benign_json", body, "body_json", "canonical",
			"q", "POST", "", "authored for the laboratory; no third-party material",
			"Well-formed JSON request body of the shape a normal client sends.")
	}
	for i := 0; i < 50; i++ {
		add(fmt.Sprintf("benign-form-%03d", i+1), "benign_form", formValues[i], "body_form",
			"canonical", "q", "POST", "", "authored for the laboratory; no third-party material",
			"Ordinary form field value submitted by a legitimate client.")
	}
	for i, q := range benignQueries {
		enc := "canonical"
		if i%5 == 0 {
			enc = "url_single"
		}
		add(fmt.Sprintf("benign-query-%03d", i+1), "benign_query", q, "query", enc, "q", "GET", "",
			"authored for the laboratory; no third-party material",
			"Legitimate search phrase; quotes and contractions test over-blocking.")
	}
	for i, h := range benignHeaders {
		add(fmt.Sprintf("benign-header-%03d", i+1), "benign_header", h.value, "header",
			"canonical", h.name, "GET", "", "authored for the laboratory; no third-party material",
			"Ordinary request header value sent by a browser or API client.")
	}
	for i, c := range benignCookies {
		add(fmt.Sprintf("benign-cookie-%03d", i+1), "benign_cookie", c.value, "cookie",
			"canonical", c.name, "GET", "", "authored for the laboratory; no third-party material",
			"Ordinary session or preference cookie value.")
	}
	for i, p := range benignPaths {
		add(fmt.Sprintf("benign-path-%03d", i+1), "benign_path", p, "path", "canonical",
			"", "GET", "/api/{probe}", "authored for the laboratory; no third-party material",
			"Ordinary resource path segment under the authorized prefix.")
	}
	return out
}
