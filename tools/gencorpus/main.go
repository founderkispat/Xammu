// Command gencorpus writes the Phase 1 effectiveness corpus. The corpus is
// committed as YAML; this program exists so the 300 attack and 300 benign cases
// are produced from one table rather than hand-edited inconsistently, and so
// growing the pool past 2,800 is a data change rather than a code change.
//
// It is not part of the xammu binary and is never run by the tool at runtime.
package main

import (
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	ID         string
	Kind       string
	Class      string
	Payload    string
	Vector     string
	Encoding   string
	Parameter  string
	Method     string
	Path       string
	Expect     string
	OWASP      string
	Provenance string
	Rationale  string
}

func main() {
	root := flag.String("out", "corpus/effectiveness", "corpus root to write")
	flag.Parse()

	attacks := buildAttacks()
	benign := buildBenign()

	files := map[string][]entry{}
	for _, e := range attacks {
		files[filepath.Join(*root, "attacks", e.Class+".yaml")] = append(
			files[filepath.Join(*root, "attacks", e.Class+".yaml")], e)
	}
	for _, e := range benign {
		files[filepath.Join(*root, "benign", strings.TrimPrefix(e.Class, "benign_")+".yaml")] = append(
			files[filepath.Join(*root, "benign", strings.TrimPrefix(e.Class, "benign_")+".yaml")], e)
	}
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	for _, p := range paths {
		if err := writeFile(p, files[p]); err != nil {
			fmt.Fprintf(os.Stderr, "gencorpus: %v\n", err)
			os.Exit(1)
		}
	}
	fmt.Printf("wrote %d attack and %d benign cases under %s\n", len(attacks), len(benign), *root)
}

func writeFile(path string, entries []entry) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# Generated by tools/gencorpus. Edit the table there, not this file.\n")
	b.WriteString("# Every payload is inert: the loader re-runs the gate before a run can send it.\n")
	for i, e := range entries {
		if i > 0 {
			b.WriteString("---\n")
		}
		writeEntry(&b, e)
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

func writeEntry(b *strings.Builder, e entry) {
	field := func(k, v string) {
		fmt.Fprintf(b, "%s: %s\n", k, strconv.Quote(v))
	}
	field("id", e.ID)
	field("kind", e.Kind)
	field("class", e.Class)
	field("payload", e.Payload)
	field("vector", e.Vector)
	field("encoding", e.Encoding)
	if e.Parameter != "" {
		field("parameter", e.Parameter)
	}
	field("method", e.Method)
	if e.Path != "" && e.Path != "/api/search" {
		field("path", e.Path)
	}
	field("expect", e.Expect)
	if e.OWASP != "" {
		field("owasp", e.OWASP)
	}
	if e.Provenance != "" {
		field("provenance", e.Provenance)
	}
	field("rationale", e.Rationale)
}

