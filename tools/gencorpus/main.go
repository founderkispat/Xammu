var classOrder = []string{
	"sqli", "xss", "path_traversal", "command_injection", "ssrf",
	"ssti", "ldap_injection", "nosql_injection", "xxe", "crlf_injection",
}

func buildAttacks() []entry {
	var out []entry
	for _, class := range classOrder {
		payloads := attackFamilies[class]
		seq := 0
		add := func(payload, vector, encoding, parameter, method, path string) {
			seq++
			out = append(out, entry{
				ID: fmt.Sprintf("%s-%03d", class, seq), Kind: "attack", Class: class,
				Payload: payload, Vector: vector, Encoding: encoding, Parameter: parameter,
				Method: method, Path: path, Expect: "blocked", OWASP: owasp[class],
				Rationale: fmt.Sprintf("Tests the %s signature in the %s transport with the %s encoding.",
					class, vector, encoding),
			})
		}
		queryEnc := []string{"canonical", "url_single", "canonical", "case_variant",
			"comment_insertion", "canonical", "whitespace_variant", "url_double",
			"canonical", "canonical"}
		for i, p := range payloads {
			add(p, "query", queryEnc[i], "q", "GET", "")
		}
		for i := 0; i < 6; i++ {
			add(payloads[i], "body_json", "canonical", "q", "POST", "")
		}
		for i := 6; i < 10; i++ {
			add(payloads[i], "body_form", "canonical", "q", "POST", "")
		}
		// User-Agent is an inspected header value; a diagnostic x-xammu-* name
		// would be outside the laboratory's rule scope and the case would measure
		// the documented gap instead of the signature.
		for i := 0; i < 5; i++ {
			add(payloads[i], "header", "canonical", "User-Agent", "GET", "")
		}
		for i := 5; i < 10; i++ {
			add(payloads[i], "cookie", "canonical", "xammu-probe", "GET", "")
		}
	}
	return out
}

